#define IDLED_VERSION  "ncz-screensaver-idled 0.1.0"
#define IDLED_LOG      "ncz-screensaver-idled: "
#define SETTINGS_SCHEMA_ID "dev.ncz.screensaver"

/* systemd exit codes. "No Wayland session right now" (logged out, compositor
 * gone or still coming up, socket missing, or a login greeter that does not
 * advertise ext-idle-notify-v1) is a transient, retriable condition:
 * EX_TEMPFAIL keeps the unit in auto-restart instead of a permanent `failed`,
 * and the session target stops it cleanly at logout. EX_CONFIG is reserved for
 * a genuine, non-retriable misconfiguration the daemon can detect before the
 * session exists (the settings schema is missing); the unit pairs it with
 * RestartPreventExitStatus=78 so it stays failed and a human notices. */
#define IDLED_EXIT_TEMPFAIL 75   /* EX_TEMPFAIL - retry when a session appears */
#define IDLED_EXIT_CONFIG   78   /* EX_CONFIG   - unfixable without reconfig */

/* Bounded startup wait. On a greetd restart the compositor can be gone, the
 * replacement can still be initialising, or WAYLAND_DISPLAY can point at the
 * greeter's session, so the first connection attempt is routinely not ready.
 * Retry for this long before handing the failure back to systemd. Overridable
 * for tests (0 = try exactly once and exit immediately). */
#define IDLED_SESSION_WAIT_DEFAULT_MS 30000u
#define IDLED_SESSION_WAIT_MAX_MS     600000u
#define IDLED_SESSION_RETRY_MS        1000u


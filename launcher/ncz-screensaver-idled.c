/* Plain snapshot of the schema fields the daemon reads. Recomputed on every
 * "changed" signal (debounced) and passed to plan_compute(). */
struct idled_settings {
    char *mode;            /* "off" | "one" | "random" | "playlist" */
    int   hack_idle_delay;
    bool  lock_enabled;
    int   lock_delay;
    bool  lock_on_suspend;
    int   display_off_delay;
};

/* Allocated plan: -1 means "no notification for this role". */
struct idled_plan {
    int  saver;
    int  lock;
    int  dpms;
    bool lock_on_suspend;
};

/* Pure: takes a settings snapshot and returns the derived plan. Used by the
 * dry-run code path too so output matches runtime behavior.
 *
 * `delegated` is set when the NCZ lock renderer is configured (the session lock
 * hosts the saver; a separate ncz-screensaver-feed renders it). In that mode
 * this daemon must not start its own wl_layer_shell saver, so `saver` is
 * disabled; the lock is requested at hack-idle-delay (the lock IS the saver),
 * regardless of lock-enabled, because the lock is the only thing that can now
 * show the saver. */
static struct idled_plan plan_compute(const struct idled_settings *s, bool delegated)
{
    struct idled_plan p = {
        .saver = -1,
        .lock  = -1,
        .dpms  = -1,
        .lock_on_suspend = s->lock_enabled && s->lock_on_suspend,
    };
    bool screensaver_on = strcmp(s->mode, "off") != 0;
    if (delegated) {
        /* The lock hosts the saver; suspend locks through the shell too. */
        p.lock_on_suspend = s->lock_on_suspend;
        if (screensaver_on) {
            p.lock = s->hack_idle_delay;
        } else if (s->lock_enabled) {
            p.lock = s->hack_idle_delay;
        }
        if (s->display_off_delay > 0) p.dpms = s->display_off_delay;
        return p;
    }
    if (screensaver_on) {
        p.saver = s->hack_idle_delay;
        if (s->lock_enabled) p.lock = s->hack_idle_delay + s->lock_delay;
    } else {
        if (s->lock_enabled) p.lock = s->hack_idle_delay;
    }
    if (s->display_off_delay > 0) p.dpms = s->display_off_delay;
    return p;
}

static void settings_clear(struct idled_settings *s)
{
    g_free(s->mode);
    s->mode = NULL;
}

static void settings_load(GSettings *settings, struct idled_settings *out)
{
    settings_clear(out);
    out->mode             = g_settings_get_string(settings, "mode");
    out->hack_idle_delay  = g_settings_get_int(settings, "hack-idle-delay");
    out->lock_enabled     = g_settings_get_boolean(settings, "lock-enabled");
    out->lock_delay       = g_settings_get_int(settings, "lock-delay");
    out->lock_on_suspend  = g_settings_get_boolean(settings, "lock-on-suspend");
    out->display_off_delay= g_settings_get_int(settings, "display-off-delay");
}


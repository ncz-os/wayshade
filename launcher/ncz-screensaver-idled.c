static void print_help(void)
{
    g_print(
"Usage: ncz-screensaver-idled [OPTIONS]\n"
"\n"
"Idle timer daemon for NCZ-OS screensaver. Subscribes to ext-idle-notify-v1\n"
"and drives the screensaver, lock and DPMS subsystems per dev.ncz.screensaver\n"
"GSettings.\n"
"\n"
"Options:\n"
"  --dry-run       Print the notification plan as JSON and exit.\n"
"  --verbose       Enable debug logging.\n"
"  --version       Print version and exit.\n"
"  --help          Print this help and exit.\n");
}

static int parse_options(int argc, char **argv, struct idled_state *st)
{
    static const struct option longopts[] = {
        { "dry-run",  no_argument, NULL, 'd' },
        { "verbose",  no_argument, NULL, 'v' },
        { "version",  no_argument, NULL, 'V' },
        { "help",     no_argument, NULL, 'h' },
        { NULL, 0, NULL, 0 },
    };
    int opt;
    while ((opt = getopt_long(argc, argv, "dvVh", longopts, NULL)) != -1) {
        switch (opt) {
        case 'd': st->opt_dry_run = true; break;
        case 'v': st->opt_verbose = true; g_verbose = true; break;
        case 'V': g_print("%s\n", IDLED_VERSION); exit(0);
        case 'h': print_help(); exit(0);
        default:  print_help(); exit(2);
        }
    }
    return optind;
}

/* ------------------------------------------------------------------------- *
 * Dry-run
 * ------------------------------------------------------------------------- */

static int run_dry_run(struct idled_state *st)
{
    if (!st->gsettings) {
        log_err("schema %s not installed", SETTINGS_SCHEMA_ID);
        return IDLED_EXIT_CONFIG;
    }
    settings_load(st->gsettings, &st->cur_settings);
    st->cur_plan = plan_compute(&st->cur_settings, st->delegated);
    char *saver_str = st->cur_plan.saver > 0 ? g_strdup_printf("%d", st->cur_plan.saver) : NULL;
    char *lock_str  = st->cur_plan.lock  > 0 ? g_strdup_printf("%d", st->cur_plan.lock)  : NULL;
    char *dpms_str  = st->cur_plan.dpms  > 0 ? g_strdup_printf("%d", st->cur_plan.dpms)  : NULL;
    GString *s = g_string_new("{");
    g_string_append_printf(s, "\"saver\":%s,", saver_str ? saver_str : "null");
    g_string_append_printf(s, "\"lock\":%s,",  lock_str  ? lock_str  : "null");
    g_string_append_printf(s, "\"dpms\":%s,",  dpms_str  ? dpms_str  : "null");
    g_string_append_printf(s, "\"lock_on_suspend\":%s",
                           st->cur_plan.lock_on_suspend ? "true" : "false");
    /* Only present in delegated mode, so the non-delegated JSON is unchanged. */
    if (st->delegated)
        g_string_append_printf(s, ",\"delegated\":true");
    g_string_append(s, "}");
    g_print("%s\n", s->str);
    g_string_free(s, TRUE);
    g_free(saver_str);
    g_free(lock_str);
    g_free(dpms_str);
    return 0;
}

/* ------------------------------------------------------------------------- *
 * main()
 * ------------------------------------------------------------------------- */

int main(int argc, char **argv)
{
    struct idled_state st;
    state_init(&st);
    parse_options(argc, argv, &st);

    /* Verify the schema is installed. If GSettings can't find it, g_settings_new
     * returns NULL; older glib returns a usable object that fails at first
     * access. We check explicitly so the diagnostic is honest. The default
     * schema source is a GLib-owned singleton and must not be unref'd. */
    GSettingsSchemaSource *source = g_settings_schema_source_get_default();
    GSettingsSchema *schema_check =
        source ? g_settings_schema_source_lookup(source, SETTINGS_SCHEMA_ID, TRUE) : NULL;
    if (!schema_check) {
        log_err("schema %s not installed", SETTINGS_SCHEMA_ID);
        state_teardown(&st);
        return IDLED_EXIT_CONFIG;
    }
    g_settings_schema_unref(schema_check);

    st.gsettings = g_settings_new(SETTINGS_SCHEMA_ID);
    if (!st.gsettings) {
        log_err("schema %s not installed", SETTINGS_SCHEMA_ID);
        state_teardown(&st);
        return IDLED_EXIT_CONFIG;
    }

    /* Delegated mode: when the NCZ lock renderer is configured the session lock
     * hosts the saver, so this daemon must not start its own. Read once at
     * startup (the conf file changes only at install time). */
    st.lock_renderer_cmd = lock_renderer_read_conf();
    st.delegated = (st.lock_renderer_cmd != NULL);
    if (st.delegated) {
        log_info("delegated mode: lock renderer configured (%s); the lock hosts "
                 "the saver and this daemon will not start one",
                 st.lock_renderer_cmd[0] ? st.lock_renderer_cmd : "<forced>");
    }

    if (st.opt_dry_run) {
        int rc = run_dry_run(&st);
        state_teardown(&st);
        return rc;
    }

    GError *err = NULL;
    int wl_rc = wl_handle_init(&st, &err);
    if (wl_rc != 0) {
        /* wl_handle_init only returns EX_TEMPFAIL: no session (or no usable
         * compositor) is retriable across a login, so systemd must keep trying
         * rather than latch the unit `failed`. */
        log_err("%s", err ? err->message : "wayland initialisation failed");
        g_clear_error(&err);
        state_teardown(&st);
        return wl_rc;
    }

    g_signal_connect(st.gsettings, "changed", G_CALLBACK(on_settings_changed), &st);

    g_unix_signal_add(SIGTERM, on_signal_term, &st);
    g_unix_signal_add(SIGINT,  on_signal_term, &st);
    g_unix_signal_add(SIGHUP,  on_signal_hup,  &st);

    logind_init(&st);

    struct idled_settings first = {0};
    settings_load(st.gsettings, &first);
    plan_apply(&st, &first); /* takes ownership of the strings in first */
    state_file_update(&st);

    GMainLoop *loop = g_main_loop_new(NULL, FALSE);
    g_loop = loop;
    if (st._shutdown) g_main_loop_quit(loop);
    g_main_loop_run(loop);
    g_loop = NULL;
    g_main_loop_unref(loop);

    int exit_code = st._exit_code;
    state_teardown(&st);
    return exit_code;
}
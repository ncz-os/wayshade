/* Per-role listener trampolines all share this struct as user data, so a
 * single listener struct can dispatch idled/resumed to the right role. */
enum notif_role { ROLE_SAVER, ROLE_LOCK, ROLE_DPMS };

struct role_data {
    struct idled_state *st;
    enum notif_role role;
};

struct idled_state {
    /* CLI / options */
    bool        opt_dry_run;
    bool        opt_verbose;

    /* Configuration */
    GSettings  *gsettings;
    struct idled_settings cur_settings;
    struct idled_plan     cur_plan;
    guint       settings_debounce;     /* g_timeout_add id; 0 = none */

    /* Delegated mode: the NCZ lock renderer is configured, so the session lock
     * hosts the saver (a separate ncz-screensaver-feed renders it) and this
     * daemon must NOT start its own wlr-layer-shell saver. It asks the shell to
     * lock at hack-idle-delay instead. See post-install/64-ncz-lock-saver-plan.sh
     * and launcher/ncz-screensaver-feed. */
    bool        delegated;
    char       *lock_renderer_cmd;     /* SINGULARITY_LOCK_RENDERER value, owned */
    GDBusConnection *session_conn;     /* org.freedesktop.ScreenSaver, lazy */

    /* Wayland */
    struct wl_display *w_display;
    GSource           *w_source;
    int                w_fd;
    bool               w_connected;
    struct wl_registry *w_registry;
    struct wl_seat     *w_seat;
    struct ext_idle_notifier_v1 *w_idle;
    /* Tracked globally to bind later when we have a registry handle. */
    uint32_t w_idle_global_name;
    uint32_t w_idle_global_version;
    bool     w_idle_global_seen;
    struct zwlr_output_power_manager_v1 *w_pwr_mgr;
    uint32_t w_pwr_mgr_global_name;
    uint32_t w_pwr_mgr_global_version;
    bool     w_pwr_mgr_global_seen;
    GArray  *w_outputs;       /* struct wl_output * */
    GArray  *w_powers;        /* struct output_power */

    /* Idle notifications, one per enabled role. NULL = not configured. */
    struct ext_idle_notification_v1 *w_saver_notif;
    struct ext_idle_notification_v1 *w_lock_notif;
    struct ext_idle_notification_v1 *w_dpms_notif;

    /* Composite DPMS state (any one notification resumed -> ON). */
    bool saver_idled;
    bool lock_idled;
    bool dpms_idled;
    bool dpms_powered_off; /* did we send off to the outputs? */

    /* Spawned children: pid < 0 means none. We reap via g_child_watch_add. */
    GPid saver_pid;
    GPid stop_pid;
    GPid lock_pid;
    guint lock_watch;
    int   lock_restarts; /* consecutive abnormal lock client exits */

    /* logind */
    GDBusConnection *logind_conn;
    GCancellable   *logind_cancellable;
    char           *logind_session_path;
    int             logind_inhibit_fd_raw;

    /* State file */
    char *state_file_path;
    char *_state_label;   /* owned */

    /* Shutdown coordination. */
    bool _shutdown;
    int  _exit_code;
};


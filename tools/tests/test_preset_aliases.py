"""Catalogue alias handling: a legacy-id preset resolves but is listed once.

The Flowerchild scene renames left the old ``butterfly-*`` ids in place as
``.conf`` aliases. ``tools/magmasimplex-schema.py`` marks each alias with an
explicit ``alias=<canonical>`` key in ``[preset]``; ``tools/generate-catalog.py``
``build_presets`` must skip those alias rows so the chooser lists each scene
once, while a conf-with-no-json saver that is *not* an alias (blackhole,
ephemeris, neonspacewar, xshadertoy_leviathan) stays listed.

No binary is needed: both tools are imported and the generated text is compared
with what is on disk.
"""

import importlib.machinery
import importlib.util
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
ASSETS = ROOT / "assets/screensaver-chooser"
PRESETS = ASSETS / "options/presets/magmasimplex"


def _load(name, rel):
    path = ROOT / rel
    loader = importlib.machinery.SourceFileLoader(name, str(path))
    spec = importlib.util.spec_from_loader(name, loader)
    mod = importlib.util.module_from_spec(spec)
    loader.exec_module(mod)
    return mod


def _schema():
    return _load("mss_alias", "tools/magmasimplex-schema.py")


def _catalog():
    return _load("gen_catalog_alias", "tools/generate-catalog.py")


def test_alias_confs_carry_the_explicit_marker():
    """Every legacy id is a .conf-only alias with an explicit alias=<id> key."""
    mod = _schema()
    assert mod.ALIASES, "the magmasimplex alias table must not be empty"
    for old, new in mod.ALIASES.items():
        conf = (PRESETS / f"{old}.conf").read_text()
        assert f"\nalias={new}\n" in conf, f"{old}: missing alias={new} marker"
        # An alias is a .conf only: no scene JSON exists for the old id.
        assert not (PRESETS / f"{old}.json").exists()


def test_schema_tool_output_matches_disk_for_alias_files():
    """The on-disk alias files are exactly what the tool would generate."""
    mod = _schema()
    files = mod.scene_files()
    for old in mod.ALIASES:
        path = PRESETS / f"{old}.conf"
        assert path.read_text() == files[path], f"{old}.conf is stale"


def test_build_presets_skips_alias_rows_only():
    """Alias rows are dropped; canonical scenes and non-alias conf-only
    savers (blackhole) stay listed, and the committed presets.tsv matches."""
    cat = _catalog()
    schema = _schema()
    ships = cat.ship_list((ROOT / "meson.build").read_text())
    rows = cat.build_presets(ROOT, ships)
    ids = [r.split("\t")[0] for r in rows]

    for old in schema.ALIASES:
        assert f"magmasimplex_gles3--{old}" not in ids, f"{old} listed twice"
    for sid in schema.SCENES:
        assert f"magmasimplex_gles3--{sid}" in ids, f"canonical {sid} missing"

    # A conf-with-no-json saver that is not an alias must stay listed.
    assert "blackhole_gles3--binary" in ids

    header = (
        "# Generated by tools/generate-catalog.py from options/presets/<hack>/*.conf\n"
        "# id\ttitle\tgroup\thack\targs\taccuracy\tdescription\tmin_gpu_class\tmeasured\n"
    )
    assert (ASSETS / "presets.tsv").read_text() == header + "\n".join(rows) + "\n"


def test_alias_target_must_be_a_canonical_scene(tmp_path):
    """An alias marker that points at nothing is a hard error, not a silent
    drop: the checker catches typos in the marker."""
    cat = _catalog()
    root = tmp_path
    pdir = root / "assets/screensaver-chooser/options/presets/demo"
    pdir.mkdir(parents=True)
    # Minimal option schema so the [demo] section validates.
    (root / "assets/screensaver-chooser/options").mkdir(parents=True, exist_ok=True)
    (root / "assets/screensaver-chooser/options/demo.tsv").write_text(
        "speed\tfloat\t1\t0\t10\t\tSpeed\tHow fast\tbasic\tDEMO_SPEED\n"
    )
    base = (
        "[preset]\nname=Ring\ndescription=A ring.\naccuracy=artistic\n"
        "min-gpu-class=weak\nsources=Original NCZ work.\nmeasured=declared\n"
    )
    (pdir / "ring.conf").write_text(base + "[demo]\nspeed=1\n")
    (pdir / "legacy.conf").write_text(base + "alias=ring\n[demo]\nspeed=1\n")
    rows = cat.build_presets(root, ["demo_gles3"])
    assert [r.split("\t")[0] for r in rows] == ["demo_gles3--ring"]
    (pdir / "broken.conf").write_text(base + "alias=missing\n[demo]\nspeed=1\n")
    try:
        cat.build_presets(root, ["demo_gles3"])
    except SystemExit as exc:
        assert "alias target" in str(exc)
    else:  # pragma: no cover - only reached if the guard is removed
        raise AssertionError("a dangling alias target must fail the build")

class GroundProfileTest(unittest.TestCase):
    """A ground piece (paper with a few marks, nearly still) must not be flagged
    flat_fill / one_color / tiny_motion; a blank ground must be flagged no_structure."""

    @staticmethod
    def _frame(w, h, marks):
        buf = bytearray([150, 146, 139] * (w * h))
        for x0, y0 in marks:
            for y in range(y0, y0 + 3):
                for x in range(x0, x0 + 40):
                    o = (y * w + x) * 3
                    buf[o : o + 3] = bytes([20, 20, 22])
        return bytes(buf)

    def test_marked_ground_passes_ground_profile(self):
        import host_test_image as hti

        w, h = 128, 64
        marks = [(8 * i, 7 * j) for i in range(1, 11) for j in range(1, 8)]
        a = self._frame(w, h, marks)
        vm = hti.visual_metrics(w, h, a, a)
        self.assertTrue(hti.visual_verdict(vm), "the default profile flags a still ground")
        self.assertEqual(hti.visual_verdict(vm, "ground"), [])

    def test_blank_ground_is_no_structure(self):
        import host_test_image as hti

        w, h = 64, 64
        a = self._frame(w, h, [])
        vm = hti.visual_metrics(w, h, a, a)
        self.assertEqual(hti.visual_verdict(vm, "ground"), ["no_structure"])


class GroundGateTest(unittest.TestCase):
    """The agent-side rules that go with the ground profile."""

    @staticmethod
    def _agent():
        import importlib.util

        path = Path(__file__).resolve().parents[1] / "host-test-agent.py"
        spec = importlib.util.spec_from_file_location("host_test_agent_mod", path)
        mod = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = mod  # dataclasses in the module look themselves up here
        spec.loader.exec_module(mod)
        return mod

    def test_moving_rule(self):
        agent = self._agent()
        still = {"motion": 0.0, "baseline_diff": 0.2}
        self.assertTrue(agent._is_moving("g", still, {"g"}))
        self.assertFalse(agent._is_moving("other", still, {"g"}))
        self.assertTrue(agent._is_moving("other", {"motion": 0.2}, set()))
        self.assertFalse(agent._is_moving("g", {"motion": 0.0, "baseline_diff": 0.0}, {"g"}))

    def test_ground_ids_parsing(self):
        import tempfile

        agent = self._agent()
        with tempfile.TemporaryDirectory() as d:
            name = str(Path(d) / "ground.tsv")
            Path(name).write_text("# comment\n\nephemeris_gles3 \treason\nother_gles3\n")
            self.assertEqual(agent._ground_ids((name,)), {"ephemeris_gles3", "other_gles3"})
        self.assertEqual(agent._ground_ids(("/nonexistent/ground.tsv",)), set())

    def test_structure_floor_boundary(self):
        import host_test_image as hti

        below = {"structured_tiles": hti.GROUND_STRUCTURE_FLOOR - 0.005}
        at = {"structured_tiles": hti.GROUND_STRUCTURE_FLOOR}
        self.assertEqual(hti.visual_verdict(below, "ground"), ["no_structure"])
        self.assertEqual(hti.visual_verdict(at, "ground"), [])
